"""What autogenerate is allowed to propose.

Separate from `env.py` because `env.py` runs migrations as a side effect of being imported, so
it cannot be imported by a test. This module is pure: it holds the rules and nothing else, and
`tests/test_autogenerate_safety.py` asserts against the same function `env.py` installs.

The defect that motivated it: `env.py` passed no `include_object`, and `make migrate`
autogenerated and applied in one command. Four tables in this database have no SQLAlchemy
model, and one of them belongs to another repository, so an unfiltered autogenerate proposed
dropping them — meaning adding a column could destroy them, unreviewed. `866f7eedb0e7`'s
docstring records a developer catching that by hand and writing the migration body manually.
"""

from __future__ import annotations

import re
from typing import Any

# Tables that exist in this database and are deliberately absent from `Base.metadata`.
# Listed by name so the reason survives in one place; rule 3 in `include_object` would catch
# them anyway.
UNMODELLED_TABLES = frozenset(
    {
        # This repo's, created by hand-written DDL and never mapped as ORM models.
        # 866f7eedb0e7:31 states this outright.
        "meeting_rooms",
        "meeting_speakers",
        "chat_messages",
        # Phase 8 Part A (e7a3c9d14b52): raw-SQL DDL, read and written with `text()`.
        "decisions",
        "action_items",
        "agent_suggestions",
        # ADR-0038 (0b91a00079a7): raw-SQL DDL, read and written with `text()`.
        "meeting_agenda_items",
        # ADR-0039 Part B (d2b3c4d5e6f7): raw-SQL DDL, read and written with `text()`.
        "meeting_templates",
        "commitments",
        "action_status_requests",
        # NOT this repo's. `mytheus-realtime` owns and migrates `transcript_chunks` in the
        # same physical Postgres (migrations/_grants.py:20-24). Dropping another repo's table
        # from this repo's autogenerate is the worst version of this bug.
        "transcript_chunks",
        # Alembic's own bookkeeping — including mytheus-realtime's second history in the
        # same database.
        "alembic_version",
    }
)

# Declarative partitions: `audit_logs_2026_07` … `audit_logs_2027_06`, `audit_logs_default`,
# `chat_messages_2026_08`. Matched by shape rather than listed, because the set grows every
# month and a list would go stale exactly when it starts mattering.
PARTITION_RE = re.compile(
    r"^(audit_logs|chat_messages|worklogs|agent_suggestions)_(\d{4}_\d{2}|default)$"
)


def _parent_table_name(obj: Any) -> str | None:
    """The table an index or constraint belongs to, if it has one."""
    table = getattr(obj, "table", None)
    return getattr(table, "name", None)


def include_object(
    obj: Any, name: str | None, type_: str, reflected: bool, compare_to: Any
) -> bool:
    """Keep autogenerate from proposing a DROP for anything this repo does not model.

    Three rules, narrowest first:

    1. Named exclusions — `UNMODELLED_TABLES`, by name.
    2. Partitions — matched by shape.
    3. The catch-all: anything reflected out of the database with no counterpart in the target
       metadata. This is the rule that actually matters, because it holds for tables nobody
       has thought of yet — a future table in another repo's history, a differently-named
       partition, a view.

    Additions and alterations pass through untouched; only the destructive direction is
    blocked. A table this repo genuinely wants to drop is dropped by writing `op.drop_table`
    in a revision by hand, which is the right amount of ceremony for destroying data.
    """
    if type_ == "table":
        if name in UNMODELLED_TABLES:
            return False
        if name is not None and PARTITION_RE.match(name):
            return False
        if reflected and compare_to is None:
            return False
        return True

    # Indexes and constraints inherit their parent table's verdict, so an excluded table does
    # not leak back in as a pile of DROP INDEX statements.
    parent = _parent_table_name(obj)
    if parent is not None and (parent in UNMODELLED_TABLES or PARTITION_RE.match(parent)):
        return False
    return True
